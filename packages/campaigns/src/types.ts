/**
 * Records of `@botmesh/campaigns`: recipients, campaign definitions, delivery states
 * (planned and settled), the inputs of the store operations and their errors.
 */

/** A potential recipient of a campaign. */
export interface CampaignRecipient {
  id: string
  tenantId: string
  channel: string
  /** Marketing opt-in; recipients without it are skipped with `opt_out`. */
  optedIn: boolean
  tags?: readonly string[]
  /** Target chat of {@link sendCampaign}; defaults to `id`. */
  chatId?: string
}

/** Campaign definition used for planning. */
export interface Campaign {
  id: string
  tenantId: string
  /** Recipients must carry all of these tags, otherwise they are skipped with `segment`. */
  requiredTags?: readonly string[]
  /**
   * Maximum successful sends per recipient for this tenant/campaign across all
   * `plan()` calls (a non-negative integer, default `1`). `0` pauses the
   * campaign: eligible recipients are skipped with reason `limit`.
   */
  maxPerRecipient?: number
}

/** Planning decision (and, once settled, send outcome) for one recipient. */
export interface Delivery {
  campaignId: string
  tenantId: string
  recipientId: string
  /**
   * `queued` until a worker settles it with {@link CampaignPlanner.markSent}
   * (`sent`) or {@link CampaignPlanner.markFailed} (`failed`).
   */
  state: 'queued' | 'sent' | 'failed' | 'skipped'
  /** Handle for settling the delivery; present on queued, sent and failed deliveries. */
  deliveryId?: string
  /**
   * Why the recipient was skipped; only present when `state` is `'skipped'`.
   * `duplicate`: repeated in this batch, or the cap is used by sent/in-flight
   * deliveries. `limit`: `maxPerRecipient` is `0`.
   */
  reason?: 'opt_out' | 'segment' | 'duplicate' | 'limit'
  /** Failure description passed to {@link CampaignPlanner.markFailed}. */
  error?: string
}

/** What {@link CampaignStore.reserve} decides for one recipient. */
export type ReservationOutcome = 'reserved' | 'duplicate' | 'limit'

/** Input of {@link CampaignStore.reserve}. */
export interface ReserveInput {
  tenantId: string
  campaignId: string
  recipientId: string
  /** Id generated by the planner (`v1.<tenant>.<campaign>.<recipient>.<uuid>`, base64url). */
  deliveryId: string
  /** Maximum successful sends per recipient (`0` pauses the campaign). */
  maxPerRecipient: number
  /** A reservation not settled by `now + ttlMs` stops reserving its slot. */
  now: number
  ttlMs: number
}

/** Outcome of {@link CampaignStore.settle}. */
export interface SettleOutcome {
  state: 'sent' | 'failed'
  error?: string
}

/** Thrown when a delivery id is unknown or was already settled. */
export class UnknownDeliveryError extends Error {
  constructor() {
    super('unknown or already settled delivery')
    this.name = 'UnknownDeliveryError'
  }
}
