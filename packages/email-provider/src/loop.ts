/**
 * Mail-loop protection. A bot that answers every email will, sooner or later,
 * answer another robot (an out-of-office, a ticketing system, a mailing list)
 * that answers back — forever. These checks follow RFC 3834 ("Recommendations
 * for Automatic Responses to Electronic Mail") plus the vendor headers seen in
 * the wild, and a per-sender rate cap as the last line of defense.
 */

import type { ParsedEmail } from './mime.js'

/** Why an inbound email was classified as automated (and therefore not answered). */
export type AutomatedReason =
  | 'auto-submitted'     // RFC 3834 Auto-Submitted: auto-replied / auto-generated / ...
  | 'mailing-list'       // List-Id / List-Unsubscribe (RFC 2919 / 2369)
  | 'precedence'         // Precedence: bulk / junk / list / auto_reply
  | 'auto-reply-header'  // X-Autoreply, X-Autorespond, X-Auto-Response-Suppress, ...
  | 'null-sender'        // Return-Path: <> (bounces, DSNs, auto-replies)
  | 'system-sender'      // MAILER-DAEMON, postmaster, no-reply, ...

const SYSTEM_LOCALPART = /^(mailer-daemon|postmaster|no-?reply|do-?not-?reply|noreply-.*|bounces?(\+.*)?|auto-?reply)$/i

/**
 * Classify an inbound email as automated. Returns the first matching reason, or
 * `undefined` for mail that looks human-written.
 */
export function detectAutomated(email: ParsedEmail): AutomatedReason | undefined {
  const autoSubmitted = email.header('auto-submitted')
  if (autoSubmitted !== undefined && autoSubmitted.split(';')[0]!.trim().toLowerCase() !== 'no') return 'auto-submitted'
  if (email.headers.has('list-id') || email.headers.has('list-unsubscribe')) return 'mailing-list'
  const precedence = email.header('precedence')?.toLowerCase()
  if (precedence && /\b(bulk|junk|list|auto_reply)\b/.test(precedence)) return 'precedence'
  if (email.headers.has('x-autoreply') || email.headers.has('x-autorespond') || email.headers.has('x-auto-reply')
    || email.headers.has('x-autogenerated') || email.headers.has('x-autoresponder')) return 'auto-reply-header'
  const suppress = email.header('x-auto-response-suppress')
  if (suppress && /\b(all|oof|autoreply)\b/i.test(suppress)) return 'auto-reply-header'
  const returnPath = email.header('return-path')
  if (returnPath !== undefined && /^<\s*>$/.test(returnPath)) return 'null-sender'
  const from = email.from?.address
  if (from) {
    const local = from.slice(0, from.lastIndexOf('@'))
    if (SYSTEM_LOCALPART.test(local)) return 'system-sender'
  }
  return undefined
}

export interface FloodGuardOptions {
  /** Max inbound messages accepted per sender inside `windowMs`. */
  max: number
  windowMs: number
}

/**
 * Sliding-window cap per sender. Catches loops with robots that send no
 * automation headers at all (two bots answering each other).
 */
export class SenderFloodGuard {
  private readonly hits = new Map<string, number[]>()

  constructor(private readonly opts: FloodGuardOptions, private readonly now: () => number = Date.now) {}

  /** Record one message from `sender`; `false` when it exceeds the cap. */
  allow(sender: string): boolean {
    const now = this.now()
    const from = now - this.opts.windowMs
    const list = (this.hits.get(sender) ?? []).filter((t) => t > from)
    if (list.length >= this.opts.max) {
      this.hits.set(sender, list)
      return false
    }
    list.push(now)
    this.hits.delete(sender) // re-insert: Map order doubles as LRU for the bound below
    this.hits.set(sender, list)
    if (this.hits.size > 10_000) {
      const oldest = this.hits.keys().next().value
      if (oldest !== undefined) this.hits.delete(oldest)
    }
    return true
  }
}
