/**
 * Public configuration and the structural seams to the optional SDKs.
 *
 * `imapflow` and `nodemailer` are OPTIONAL peer dependencies, loaded lazily on
 * first use. The provider only relies on the small structural interfaces below
 * (`ImapClientLike`, `SmtpTransportLike`), so tests — and hosts with their own
 * clients — inject fakes via `createImapClient` / `smtpTransport`.
 */

import type { LoggerLike, MediaRef } from '@botmesh/core'
import type { SecureFetchOptions } from '@botmesh/http'
import type { EmailAddress } from './address.js'
import type { AutomatedReason, FloodGuardOptions } from './loop.js'
import type { EmailThreadingMode, EmailThreadStore } from './threading.js'

/* ----------------------------------------------------------------- IMAP seam */

export interface ImapFetchedMessage {
  uid: number
  /** Full RFC 822 source (requested with `{ source: true }`). */
  source?: Buffer | Uint8Array
  /** RFC 822 size in bytes (requested with `{ size: true }`). */
  size?: number
  internalDate?: Date | string
}

export interface ImapMailboxLock {
  release(): void
}

/** The subset of `imapflow`'s `ImapFlow` the provider uses. */
export interface ImapClientLike {
  connect(): Promise<void>
  logout(): Promise<void>
  close?(): void
  getMailboxLock(path: string): Promise<ImapMailboxLock>
  search(query: Record<string, unknown>, options?: { uid?: boolean }): Promise<number[] | false>
  fetch(range: string | number[], query: Record<string, unknown>, options?: { uid?: boolean }): AsyncIterable<ImapFetchedMessage>
  messageFlagsAdd(range: string | number[], flags: string[], options?: { uid?: boolean }): Promise<unknown>
  on(event: string, listener: (...args: unknown[]) => void): unknown
  readonly mailbox?: { uidNext?: number; uidValidity?: bigint | number } | false | null
}

/* ----------------------------------------------------------------- SMTP seam */

export interface SmtpAttachment {
  filename?: string
  content: Buffer
  contentType?: string
  /** Content-ID for inline images referenced from HTML as `cid:`. */
  cid?: string
}

/** The nodemailer `sendMail` options the provider produces (a compatible subset). */
export interface SmtpMailOptions {
  from: EmailAddress | string
  to: EmailAddress | string
  cc?: string | string[]
  bcc?: string | string[]
  subject: string
  text: string
  html?: string
  attachments?: SmtpAttachment[]
  /** `<id@domain>` — generated by the provider so the thread index knows it before sending. */
  messageId: string
  inReplyTo?: string
  references?: string[]
  headers: Record<string, string>
}

export interface SmtpSendInfo {
  messageId?: string
  accepted?: unknown[]
  rejected?: unknown[]
  response?: string
}

/** The subset of a nodemailer `Transporter` the provider uses. */
export interface SmtpTransportLike {
  sendMail(mail: SmtpMailOptions): Promise<SmtpSendInfo>
  verify?(): Promise<unknown>
  close?(): void
}

/* ----------------------------------------------------------------- config */

export interface ImapConnectionOptions {
  host: string
  /** Default 993. */
  port?: number
  /** TLS from the start. Default `true` unless `port === 143`. */
  secure?: boolean
  user: string
  pass?: string
  /** OAuth2 access token (XOAUTH2) instead of `pass` — Gmail / Microsoft 365. */
  accessToken?: string
  /** Mailbox to watch. Default `INBOX`. */
  mailbox?: string
  /** Extra options forwarded verbatim to `new ImapFlow(...)` (the provider defaults `autoIdleDelay` to 1000 ms). */
  options?: Record<string, unknown>
}

export interface SmtpConnectionOptions {
  host: string
  /** Default 465. */
  port?: number
  /** Implicit TLS. Default `true` when `port === 465`; otherwise STARTTLS. */
  secure?: boolean
  user?: string
  pass?: string
  /** OAuth2 access token (XOAUTH2) instead of `pass`. */
  accessToken?: string
  /** Run `transport.verify()` on `start()` (fail fast on bad credentials). Default false. */
  verify?: boolean
  /** Extra options forwarded verbatim to `nodemailer.createTransport(...)`. */
  options?: Record<string, unknown>
}

export interface EmailLoopProtectionOptions {
  /** Automated-mail reasons to let through anyway (e.g. `['mailing-list']`). */
  ignore?: AutomatedReason[]
  /** Per-sender inbound cap. Default `{ max: 30, windowMs: 3_600_000 }`; `false` disables it. */
  maxPerSender?: FloodGuardOptions | false
}

export interface EmailProviderConfig {
  /** IMAP account to watch (IDLE). Omit for an ingest-only / send-only provider. */
  imap?: ImapConnectionOptions
  /** SMTP account to send from. */
  smtp?: SmtpConnectionOptions
  /** The bot's own address: `From` of outbound mail and `selfId`. Defaults to `smtp.user` / `imap.user` when they are addresses. */
  address?: string
  /** Display name for `From`. */
  fromName?: string
  /** Override the IMAP client factory (called on every (re)connect; IMAP clients are single-use). */
  createImapClient?: () => ImapClientLike | Promise<ImapClientLike>
  /** Override the SMTP transport (e.g. an already-configured nodemailer transporter). */
  smtpTransport?: SmtpTransportLike
  /** `thread` (default): one chat per email thread. `sender`: one chat per correspondent. */
  threading?: EmailThreadingMode
  /** Where thread state lives. Default: bounded in memory. See `cursorThreadStore`. */
  threadStore?: EmailThreadStore
  /** Subject for mail that starts a new thread without one. Default `'(no subject)'`. */
  defaultSubject?: string
  /** Remove quoted history and signatures from `body`. Default true (`raw.text` keeps everything). */
  stripQuotes?: boolean
  /** What to do with mail already in the mailbox at first connect. Default `'unseen'`. */
  processExisting?: 'unseen' | 'none'
  /** Flag processed messages `\Seen`. Default true. */
  markSeen?: boolean
  /** Inbound loop protection. Default on; `false` disables every check (not recommended). */
  loopProtection?: EmailLoopProtectionOptions | false
  /** `Auto-Submitted` value stamped on outbound mail (RFC 3834). Default `'auto-replied'`; `false` omits it. */
  autoSubmitted?: string | false
  /** Refuse to send to addresses that hard-bounced. Default true. */
  suppressBounced?: boolean
  /** Max total outbound attachment bytes per email. Default 25 MiB. */
  maxAttachmentBytes?: number
  /** Inbound attachment bytes kept in memory for `downloadMedia`. Default 32 MiB (older ones are refetched over IMAP). */
  attachmentCacheBytes?: number
  /**
   * Max size of one inbound email (RFC 822 bytes). Larger mail is skipped before
   * it is downloaded over IMAP (and flagged `\Seen` when `markSeen`), and
   * `ingest()` answers it with status 413. Default 40 MiB.
   */
  maxInboundBytes?: number
  /**
   * When to send replies to the `Reply-To` address instead of `From`.
   * `'same-domain'` (default): only when Reply-To is in the From address's
   * domain, so a forged header cannot redirect a correspondent's replies to
   * a third party. `'always'` trusts it; `'never'` always answers `From`.
   */
  replyTo?: 'same-domain' | 'always' | 'never'
  /**
   * Only accept inbound mail that your receiving MTA authenticated. Reads the
   * `Authentication-Results` headers stamped by `authservId` (others are
   * ignored: anyone can add one) and requires `dmarc=pass`, or `dkim=pass`
   * with `header.d` aligned to the From domain. Rejected mail is skipped with
   * reason `'unauthenticated'`. Off by default: `From` is then unauthenticated.
   */
  requireAuthentication?: { authservId: string }
  /** IMAP reconnect backoff. Default `{ baseMs: 1000, maxMs: 60000 }`. */
  reconnect?: { baseMs?: number; maxMs?: number }
  /** Options for `secureFetch` when an outbound attachment is a URL. */
  http?: SecureFetchOptions
  logger?: LoggerLike
  debug?: boolean
}

/* ----------------------------------------------------------------- raw */

/** Provider-native payload on `InboundMessage.raw` (`ctx.raw`). */
export interface EmailRaw {
  messageId?: string
  inReplyTo?: string
  references: string[]
  /** Full subject, prefixes included. */
  subject: string
  from?: EmailAddress
  to: EmailAddress[]
  cc: EmailAddress[]
  replyTo: EmailAddress[]
  /** ISO date from the `Date` header. */
  date?: string
  /** Full plain-text body (quotes included). */
  text?: string
  html?: string
  /** Every attachment (inline images included), downloadable via `provider.downloadMedia`. */
  attachments: MediaRef[]
  /** Raw (unfolded) headers, lower-cased names. */
  headers: Record<string, string[]>
  uid?: number
  mailbox?: string
}

/** `MediaRef.token` for email attachments. */
export interface EmailMediaToken {
  messageId: string
  index: number
  /** Truncated SHA-256 of the attachment bytes (cache key and refetch check). */
  digest: string
  uid?: number
  /** Mailbox UIDVALIDITY when `uid` was read; the UID is only refetched while it matches. */
  uidValidity?: string
}
