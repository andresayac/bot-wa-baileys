/**
 * Project templates for `create-bot-wa`.
 *
 * Each template is a pure string-builder set: given a package name it
 * returns the full file list of a runnable @bot-wa project (package.json,
 * src/bot.js, .env.example, .gitignore, README.md). No I/O here — see
 * `scaffold.ts` for the writer.
 */

export type TemplateName = 'baileys' | 'meta' | 'telegram' | 'ai'

/** One file to write into the generated project. */
export interface TemplateFile {
  /** Repo-relative POSIX path, e.g. `src/bot.js`. */
  path: string
  contents: string
}

export interface ProjectTemplate {
  name: TemplateName
  /** Human-readable label, e.g. `WhatsApp · Baileys`. */
  label: string
  description: string
  /** Build every file for a project named `name`. */
  files: (name: string) => TemplateFile[]
}

/* Versions stamped into generated package.json files.
 *
 * These track the CURRENT published line. While core is on the alpha line, a
 * caret over a prerelease (`^2.0.0-alpha.1`) only matches other `2.0.0-*`
 * prereleases, NOT a future stable `2.0.0` — so re-stamp CORE_VERSION to
 * `^2.0.0` (drop the prerelease) as part of the stable release. Until the
 * `@bot-wa/*` packages are published to npm, generated projects install only
 * against a registry/local mirror that has them. */
const CORE_VERSION = '^2.0.0-alpha.1'
const TRANSPORT_VERSION = '^0.1.0'
const ANTHROPIC_SDK_VERSION = '^0.68.0'

/* Shared builders -------------------------------------------------------- */

const GITIGNORE = ['node_modules/', 'sessions/', '.env', '*.qr.png', ''].join('\n')

function packageJson(name: string, deps: Record<string, string>): string {
  const pkg = {
    name,
    version: '0.1.0',
    private: true,
    type: 'module',
    description: 'A bot built with @bot-wa/core',
    engines: { node: '>=22' },
    scripts: {
      start: 'node --env-file=.env src/bot.js',
      // Terminal chat simulator with hot reload (ships with @bot-wa/core).
      dev: 'bot-wa dev src/bot.js --env-file .env',
    },
    dependencies: deps,
  }
  return JSON.stringify(pkg, null, 2) + '\n'
}

