/**
 * Project templates for `create-bot-wa`.
 *
 * Each template is a pure string-builder set: given a package name it
 * returns the full file list of a runnable @bot-wa project (package.json,
 * src/bot.js, .env.example, .gitignore, README.md). No I/O here — see
 * `scaffold.ts` for the writer.
 */

export type TemplateName = 'baileys' | 'meta' | 'telegram' | 'ai'

/** One file to write into the generated project. */
export interface TemplateFile {
  /** Repo-relative POSIX path, e.g. `src/bot.js`. */
  path: string
  contents: string
}

export interface ProjectTemplate {
  name: TemplateName
  /** Human-readable label, e.g. `WhatsApp · Baileys`. */
  label: string
  description: string
  /** Build every file for a project named `name`. */
  files: (name: string) => TemplateFile[]
}

/* Versions stamped into generated package.json files. */
const CORE_VERSION = '^2.0.0-alpha.1'
const TRANSPORT_VERSION = '^0.1.0'
const ANTHROPIC_SDK_VERSION = '^0.68.0'

/* Shared builders -------------------------------------------------------- */

const GITIGNORE = ['node_modules/', 'sessions/', '.env', '*.qr.png', ''].join('\n')

function packageJson(name: string, deps: Record<string, string>): string {
  const pkg = {
    name,
    version: '0.1.0',
    private: true,
    type: 'module',
    description: 'A bot built with @bot-wa/core',
    engines: { node: '>=20.6.0' },
    scripts: {
      start: 'node --env-file=.env src/bot.js',
      dev: 'node --env-file=.env --watch src/bot.js',
    },
    dependencies: deps,
  }
  return JSON.stringify(pkg, null, 2) + '\n'
}

/** The /hola handler + a tiny menu flow shared by every template's bot.js. */
const HANDLERS = [
  "// Simple keyword handler — reply 'hola' and get a greeting.",
  "bot.when('hola', async (ctx) => await ctx.reply('¡Hola! 👋'))",
  '',
  '// A small conversational flow: ask a question, capture the answer, reply.',
  'bot.useFlow(',
  "  flow('menu')",
  "    .say('📋 *Menú*\\n1️⃣ Info\\n2️⃣ Ping')",
  "    .ask('Responde 1 o 2:', 'choice')",
  "    .say(async (_msg, c) => (c.state.choice === '1' ? 'ℹ️ Hecho con @bot-wa/core' : '🏓 ¡pong!')),",
  ')',
]

function readme(name: string, label: string, description: string, notes: string[]): string {
  const fence = '```'
  return [
    '# ' + name,
    '',
    '> ' + description,
    '',
    'Template: **' + label + '** — generated by [`create-bot-wa`](https://www.npmjs.com/package/create-bot-wa).',
    '',
    '## Run',
    '',
    fence + 'bash',
    'npm install          # or: pnpm install',
    'cp .env.example .env # then fill in your credentials',
    'npm start            # or: npm run dev (auto-reload)',
    fence,
    '',
    ...notes,
    '',
    '## Structure',
    '',
    '- `src/bot.js` — your bot: provider + handlers + flows.',
    '- `.env.example` — the env vars this bot reads (copy to `.env`, never commit `.env`).',
    '- `sessions/` — auth artifacts (gitignored).',
    '',
    '## Learn more',
    '',
    '- [`@bot-wa/core`](https://www.npmjs.com/package/@bot-wa/core) — `when`, `flow`, `conversation`, plugins, hooks, scheduler.',
    '',
  ].join('\n')
}

