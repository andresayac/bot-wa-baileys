const baileys: ProjectTemplate = {
  name: 'baileys',
  label: 'WhatsApp · Baileys',
  description: 'WhatsApp bot over the Baileys socket (QR login, no Meta account needed).',
  files: (name) => [
    {
      path: 'package.json',
      contents: packageJson(name, {
        '@bot-wa/core': CORE_VERSION,
        '@bot-wa/baileys': TRANSPORT_VERSION,
      }),
    },
    {
      path: 'src/bot.js',
      contents:
        [
          "import { Bot, flow } from '@bot-wa/core'",
          "import { BaileysProvider } from '@bot-wa/baileys'",
          '',
          '// Secrets/config come from .env (loaded via `node --env-file=.env`).',
          "// The session name just picks which sessions/<name> auth folder to use.",
          'const bot = new Bot({',
          "  provider: new BaileysProvider({ session: process.env.BOT_SESSION ?? 'my-bot' }),",
          '})',
          '',
          "bot.on('qr', (qr) => bot.logger.info('Scan the QR to link WhatsApp: ' + qr))",
          "bot.on('ready', () => bot.logger.info('✅ Bot connected — send it \"hola\"'))",
          '',
          ...HANDLERS,
          '',
          'await bot.start()',
          '',
        ].join('\n'),
    },
    {
      path: '.env.example',
      contents: ['# Session/auth folder name (sessions/<name>). No other secrets needed for Baileys.', 'BOT_SESSION=my-bot', ''].join('\n'),
    },
    { path: '.gitignore', contents: GITIGNORE },
    {
      path: 'README.md',
      contents: readme(name, baileysLabel(), baileys.description, [
        'On first start a **QR code** is printed — scan it with WhatsApp → Linked devices.',
        'Auth is cached under `sessions/` so later starts connect automatically.',
      ]),
    },
  ],
}
