#!/usr/bin/env node
/**
 * Generates src/versions.ts: the `@bot-wa/*` dependency ranges stamped into
 * scaffolded projects, derived from the CURRENT version of every public
 * workspace package (packages/* package.json, `private` ones skipped).
 *
 * Each range is a caret over the exact version (`^2.0.0-alpha.2`). npm only
 * lets a prerelease satisfy a range whose comparator names a prerelease on the
 * same major.minor.patch, so a hand-written `^0.1.0` would NOT install
 * `0.1.1-alpha.0`; `^0.1.1-alpha.0` does, and still accepts the stable `0.1.1`.
 *
 *   node scripts/gen-versions.mjs            # (re)write src/versions.ts — runs on `pnpm build`
 *   node scripts/gen-versions.mjs --check    # exit 1 if src/versions.ts is out of date
 *   --root <repo> --out <file>               # alternative workspace / output (tests)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const PKG_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const argv = process.argv.slice(2)
const opt = (flag) => {
  const i = argv.indexOf(flag)
  return i >= 0 ? argv[i + 1] : undefined
}
const root = resolve(opt('--root') ?? join(PKG_DIR, '..', '..'))
const out = resolve(opt('--out') ?? join(PKG_DIR, 'src', 'versions.ts'))
const check = argv.includes('--check')

const versions = []
for (const dir of readdirSync(join(root, 'packages'))) {
  const file = join(root, 'packages', dir, 'package.json')
  if (!existsSync(file)) continue
  const pkg = JSON.parse(readFileSync(file, 'utf8'))
  if (pkg.private || typeof pkg.name !== 'string' || !pkg.name.startsWith('@bot-wa/')) continue
  versions.push([pkg.name, `^${pkg.version}`])
}
versions.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))

const source = [
  '// GENERATED by scripts/gen-versions.mjs from the workspace package.json files.',
  '// Do not edit: `pnpm build` regenerates it (and `pnpm version-packages` after a bump).',
  '',
  '/** Dependency range stamped into scaffolded projects for each public `@bot-wa/*` package. */',
  'export const BOTWA_VERSIONS = {',
  ...versions.map(([name, range]) => `  '${name}': '${range}',`),
  '} as const',
  '',
  '/** A public `@bot-wa/*` package name. */',
  'export type BotWaPackage = keyof typeof BOTWA_VERSIONS',
  '',
].join('\n')

const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : undefined
if (check) {
  if (current !== source) {
    process.stderr.write(`${out} is out of date: run \`node packages/create-bot-wa/scripts/gen-versions.mjs\` (or \`pnpm build\`)\n`)
    process.exit(1)
  }
} else if (current !== source) {
  writeFileSync(out, source)
}
